// Command simulate-flow plays back a student's full learning loop end-to-end:
//
//	搜题 → 真实模型解答 → 回拨历史时间落库 → 长期记忆提取(L0/L1/L2/L3)
//	→ 遗忘边界(可回忆概率跌破阈值) → 防遗忘计划建单 → 发题提醒复习
//
// The solving step uses the configured Bailian model for real answers; the
// memory extractor is deterministic so the run needs no live extraction LLM.
// Doing-times are back-dated (2 / 20 / 42 days ago) so forgetting genuinely
// crosses the recall threshold and the review reminder fires for real.
